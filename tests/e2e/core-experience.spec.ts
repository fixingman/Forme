import {test,expect} from '@playwright/test';
import snapshot from '../fixtures/vinted.json';
test.beforeEach(async({page})=>{
 await page.route('**/api/size-profile',route=>route.fulfill({json:{profile:null}}));
 await page.route('**/api/listings',route=>route.fulfill({json:snapshot}));
 await page.route('**/api/refresh',route=>route.fulfill({status:503,json:{error:'Isolated test'}}));
 await page.route('**/api/local-profile',route=>route.fulfill({status:503,json:{error:'Isolated test'}}));
});
test('first visit resumes setup and saves brand, department and size choices',async({page})=>{
 await page.goto('/');
 await expect(page).toHaveURL(/\/welcome$/);
 await page.goto('/');await expect(page).toHaveURL(/\/welcome$/);
 await page.getByRole('button',{name:'Lemaire',exact:true}).click();
 await page.getByRole('button',{name:'Continue',exact:false}).click();
 await expect(page).toHaveURL(/step=departments/);
 await page.getByLabel('Women',{exact:true}).uncheck();
 await page.getByLabel('Men',{exact:true}).check();
 await page.getByLabel('Unisex',{exact:true}).check();
 await page.getByLabel('Include items with an unknown department',{exact:true}).uncheck();
 await page.getByRole('button',{name:'Continue',exact:false}).click();
 await expect(page).toHaveURL(/step=sizes/);
 await page.goBack();await expect(page).toHaveURL(/step=departments/);
 await expect(page.getByLabel('Women',{exact:true})).not.toBeChecked();
 await page.goForward();await expect(page).toHaveURL(/step=sizes/);
 await page.getByRole('button',{name:'M',exact:true}).click();
 await page.getByRole('button',{name:'Finish setup',exact:true}).click();
 await expect(page).toHaveURL(/\/discover$/);
 await page.reload();await expect(page.getByRole('heading',{name:'Discover',exact:true})).toBeVisible();
 const preferences=await page.evaluate(()=>JSON.parse(localStorage.getItem('forme-v2')!));
 expect(preferences.following).toEqual(['Lemaire']);expect(preferences.gender.selected.sort()).toEqual(['men','unisex']);expect(preferences.gender.includeUnknown).toBe(false);expect(preferences.sizing.groups.clothing).toContain('M');
 expect(await page.evaluate(()=>localStorage.getItem('forme-onboarding-pending'))).toBeNull();
});
test('returning users keep preferences, clean navigation and accessible collection tools',async({page})=>{
 await page.addInitScript(()=>{if(!localStorage.getItem('forme-v2'))localStorage.setItem('forme-v2',JSON.stringify({following:['Lemaire'],excluded:['Zara'],saved:[6],styles:['Minimalism']}));});
 await page.goto('/');await expect(page.getByRole('heading',{name:'Home',exact:true})).toBeVisible();
 const nav=page.getByRole('navigation',{name:'Main navigation'});
 await expect(nav.getByRole('link',{name:'Rare Finds',exact:true})).toHaveCount(0);
 await expect(nav.getByRole('link',{name:'Daily Drops',exact:true})).toHaveCount(0);
 await page.goto('/settings');
 await expect(page.getByLabel('Listing data')).toHaveCount(0);
 await page.getByRole('link',{name:/^Collection tools/}).click();
 await expect(page.getByRole('heading',{name:'Collection tools',exact:true})).toBeVisible();
 await expect(page.getByLabel('Listing data')).toBeVisible();
 const preferences=await page.evaluate(()=>JSON.parse(localStorage.getItem('forme-v2')!));
 expect(preferences.following).toEqual(['Lemaire']);expect(preferences.excluded).toEqual(['Zara']);expect(preferences.saved).toEqual([6]);
});
test('a failed collection can retry and unavailable photos do not break cards',async({page})=>{
 await page.addInitScript(()=>{localStorage.setItem('forme-onboarding-complete','1');});
 await page.route('**/api/listings',route=>route.fulfill({status:503}));
 await page.route('**/data/vinted.json',route=>route.fulfill({status:503}));
 await page.goto('/following');
 await expect(page.getByRole('button',{name:'Retry listings'})).toBeVisible();
 await page.route('**/api/listings',route=>route.fulfill({json:snapshot}));
 await page.route(snapshot.items[0].imageUrl,route=>route.abort());
 await page.getByRole('button',{name:'Retry listings'}).click();
 await expect(page.getByRole('button',{name:'Retry listings'})).toHaveCount(0);
 const card=page.getByTestId(`listing-${snapshot.items[0].id}`);
 await expect(card).toBeVisible();await expect(card.getByText('Photo unavailable',{exact:true})).toBeVisible();
 await card.getByRole('button',{name:`Save ${snapshot.items[0].brand} ${snapshot.items[0].title}`,exact:true}).click();
 await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Saved Items',exact:true}).click();
 await expect(card).toBeVisible();
});
